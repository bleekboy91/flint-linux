# ─────────────────────────────────────────────────────────────────────────────
# PHASE 2 — CHROOT FINAL SYSTEM
# ─────────────────────────────────────────────────────────────────────────────
phase2_chroot_system() {
    banner "Phase 2 — Building Final System (chroot)"

    local CHROOT_SCRIPT="${LFS}/sources/flint_phase2.sh"
    _write_phase2_script "${CHROOT_SCRIPT}"
    chmod +x "${CHROOT_SCRIPT}"

    chroot "${LFS}" /usr/bin/env -i \
        HOME=/root                  \
        TERM="${TERM}"              \
        PS1='(flint chroot) \u:\w\$ ' \
        PATH=/usr/bin:/usr/sbin     \
        MAKEFLAGS="-j$(nproc)"      \
        CFLAGS="-march=skylake -mtune=skylake -O2 -pipe -fno-plt" \
        CXXFLAGS="-march=skylake -mtune=skylake -O2 -pipe -fno-plt" \
        LDFLAGS="-Wl,-O1,--sort-common,--as-needed,-z,relro,-z,now" \
        /bin/bash --login /sources/flint_phase2.sh
}

_write_phase2_script() {
    local script_path="$1"
    cat > "${script_path}" <<'CHROOT_SCRIPT'
#!/usr/bin/env bash
set -euo pipefail

NPROC=$(nproc)
SRC="/sources"
STATE="/flint_state"
LOGS="/flint_logs"
CFLAGS="-march=skylake -mtune=skylake -O2 -pipe -fno-plt"
CXXFLAGS="${CFLAGS}"
LDFLAGS="-Wl,-O1,--sort-common,--as-needed,-z,relro,-z,now"
MAKEFLAGS="-j${NPROC}"
export CFLAGS CXXFLAGS LDFLAGS MAKEFLAGS

step_done()    { mkdir -p "${STATE}"; touch "${STATE}/$1.done"; echo "  ✓ $1"; }
step_is_done() { [[ -f "${STATE}/$1.done" ]]; }
run_step() {
    local s="$1" d="$2"; shift 2
    step_is_done "${s}" && { echo "  → Skip: ${d}"; return 0; }
    echo "[P2] ${d}"
    mkdir -p "${LOGS}"
    "$@" 2>&1 | tee "${LOGS}/${s}.log"
    step_done "${s}"
}
extr() {
    cd /tmp
    rm -rf build_pkg 2>/dev/null; mkdir build_pkg; cd build_pkg
    tar xf "${SRC}/$1"
    cd "$(tar tf "${SRC}/$1" | head -1 | cut -d/ -f1)"
}

