# UNMOUNT AND CLEANUP
# ─────────────────────────────────────────────────────────────────────────────
cleanup_mounts() {
    banner "Unmounting virtual filesystems"
    local mounts=(
        "${LFS}/dev/pts"
        "${LFS}/dev/shm"
        "${LFS}/dev"
        "${LFS}/proc"
        "${LFS}/run"
        "${LFS}/sys"
    )
    for m in "${mounts[@]}"; do
        if mountpoint -q "${m}" 2>/dev/null; then
            umount -v "${m}" || umount -vl "${m}"
        fi
    done
    success "Mounts cleaned up."
}

