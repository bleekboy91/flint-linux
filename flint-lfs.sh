_create_dirs() {
    mkdir -p "${LFS}"/{sources,tools,flint_state,flint_logs}
    mkdir -p /tmp/flint_build
    chmod a+wt "${SOURCES_DIR}"
    # LFS book directory structure
    mkdir -p "${LFS}"/{boot,etc/{opt,profile.d},home,lib/firmware,lib64}
    mkdir -p "${LFS}"/{media/{floppy,cdrom},mnt,opt,proc,run}
    mkdir -p "${LFS}"/{srv,sys,tmp,usr,var}
    mkdir -p "${LFS}"/usr/{bin,include,lib,lib64,libexec,local,sbin,share,src}
    mkdir -p "${LFS}"/usr/local/{bin,include,lib,sbin,share}
    mkdir -p "${LFS}"/usr/share/{color,dict,doc,info,locale,man}
    mkdir -p "${LFS}"/usr/share/{misc,terminfo,zoneinfo}
    mkdir -p "${LFS}"/usr/share/man/man{1..8}
    mkdir -p "${LFS}"/var/{cache,lib,local,log,mail,opt,spool,tmp}
    install -dv -m 0750 "${LFS}"/root
    install -dv -m 1777 "${LFS}"/tmp "${LFS}"/var/tmp
    # Create essential symlinks
    ln -sfn usr/bin "${LFS}"/bin
    ln -sfn usr/bin "${LFS}"/sbin
    ln -sfn usr/lib "${LFS}"/lib
    ln -sfn usr/lib64 "${LFS}"/lib64
    ln -sfn usr/sbin "${LFS}"/usr/sbin  2>/dev/null || true
    # Compatibility
    ln -sfn /proc/self/mounts "${LFS}"/etc/mtab 2>/dev/null || true
}

_create_lfs_user() {
    if ! id lfs &>/dev/null; then
        groupadd lfs 2>/dev/null || true
        useradd -s /bin/bash -g lfs -m -k /dev/null lfs
    fi
    chown -R lfs:lfs "${LFS}"/tools "${SOURCES_DIR}" 2>/dev/null || true
    chown lfs:lfs "${LFS}" 2>/dev/null || true

    # lfs user bashrc
    cat > /home/lfs/.bash_profile <<'EOF'
exec env -i HOME=$HOME TERM=$TERM PS1='\u:\w\$ ' /bin/bash
EOF
    cat > /home/lfs/.bashrc <<EOF
set +h
umask 022
LFS=${LFS}
LC_ALL=POSIX
LFS_TGT=${LFS_TGT}
PATH=/usr/bin:/bin:/usr/sbin:/sbin:\${LFS}/tools/bin
CONFIG_SITE=\${LFS}/usr/share/config.site
CFLAGS="${CFLAGS}"
CXXFLAGS="${CXXFLAGS}"
LDFLAGS="${LDFLAGS}"
MAKEFLAGS="${MAKEFLAGS}"
export LFS LC_ALL LFS_TGT PATH CONFIG_SITE CFLAGS CXXFLAGS LDFLAGS MAKEFLAGS
EOF
    chown lfs:lfs /home/lfs/.bash_profile /home/lfs/.bashrc
}

_create_symlinks() {
    # /tools lives inside $LFS for chroot compatibility
    [[ -d "${LFS}/tools" ]] || mkdir -p "${LFS}/tools"
    ln -sfn "${LFS}/tools" /tools 2>/dev/null || true
}

