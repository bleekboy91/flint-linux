logfile = /var/log/dinit/getty.log
DINIT_GETTY

    cat > /etc/dinit.d/sshd <<'DINIT_SSHD'
type = process
command = /usr/sbin/sshd -D
restart = true
DINIT_SSHD

    cat > /etc/dinit.d/networking <<'DINIT_NET'
type = scripted
command = /etc/dinit.d/scripts/networking.sh
DINIT_NET

    mkdir -p /etc/dinit.d/scripts /var/log/dinit

    cat > /etc/dinit.d/scripts/boot.sh <<'BOOT_SH'
#!/bin/bash
# Flint Linux boot sequence
mount -o remount,rw /
mount -a
swapon -a

# Hostname
echo "flint" > /proc/sys/kernel/hostname

# Locale
export LANG=en_US.UTF-8
export LC_ALL=en_US.UTF-8

# System clock
hwclock --hctosys 2>/dev/null || true

# Activate zram swap
modprobe zram
echo lz4 > /sys/block/zram0/comp_algorithm
echo 4G  > /sys/block/zram0/disksize
mkswap /dev/zram0
swapon -p 100 /dev/zram0

# Kernel tunables for performance
sysctl -w vm.swappiness=10
sysctl -w vm.vfs_cache_pressure=50
sysctl -w kernel.nmi_watchdog=0
sysctl -w net.core.netdev_max_backlog=16384
BOOT_SH
    chmod +x /etc/dinit.d/scripts/boot.sh

    cat > /etc/dinit.d/scripts/networking.sh <<'NET_SH'
#!/bin/bash
ip link set lo up
# DHCP on first ethernet (adjust interface name post-boot)
ip link set eth0 up 2>/dev/null || true
dhcpcd eth0 2>/dev/null || true
NET_SH
    chmod +x /etc/dinit.d/scripts/networking.sh

    # Link dinit as /sbin/init
    ln -sfv /usr/sbin/dinit /sbin/init
}
