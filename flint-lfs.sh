_configure_zram_service() {
    # dinit service for zram
    local dinit_dir="${LFS}/etc/dinit.d"
    mkdir -p "${dinit_dir}/scripts"

    cat > "${dinit_dir}/zram-swap" <<'EOF'
type = scripted
command = /etc/dinit.d/scripts/zram-setup.sh
before = boot
logfile = /var/log/dinit/zram.log
EOF

    cat > "${dinit_dir}/scripts/zram-setup.sh" <<'EOF'
#!/bin/bash
# Flint Linux — Zram swap setup (4GB compressed swap on 12GB RAM machine)
set -e

ZRAM_SIZE="4G"
ZRAM_ALGO="lz4"    # lz4 is fastest; use zstd for better compression
ZRAM_PRIORITY=100  # Higher than disk swap

modprobe zram num_devices=1

# Set compression algorithm
echo "${ZRAM_ALGO}" > /sys/block/zram0/comp_algorithm

# Set disk size
echo "${ZRAM_SIZE}" > /sys/block/zram0/disksize

# Optional: multi-stream compression (uses more CPU, better throughput)
echo "$(nproc)" > /sys/block/zram0/max_comp_streams 2>/dev/null || true

# Format and activate
mkswap --label zram0 /dev/zram0
swapon --priority "${ZRAM_PRIORITY}" /dev/zram0

echo "Zram swap activated: ${ZRAM_SIZE} (${ZRAM_ALGO})"
EOF
    chmod +x "${dinit_dir}/scripts/zram-setup.sh"
}

