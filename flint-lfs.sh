build_dinit() {
    extr "dinit-0.19.1.tar.gz"
    make -j"${NPROC}"           \
        CXXFLAGS="${CXXFLAGS}"  \
        LDFLAGS="${LDFLAGS}"    \
        SBINDIR=/usr/sbin       \
        SYSCONTROLSOCKET=/run/dinitctl
    make install SBINDIR=/usr/sbin
    install -dm755 /etc/dinit.d

    # System service definitions
    cat > /etc/dinit.d/boot <<'DINIT_BOOT'
type = scripted
command = /etc/dinit.d/scripts/boot.sh
