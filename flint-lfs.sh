# Mark a step as done
step_done() {
    local step="$1"
    mkdir -p "${STATE_DIR}"
    touch "${STATE_DIR}/${step}.done"
    success "Step '${step}' complete."
}

# Check if a step is already done
step_is_done() {
    local step="$1"
    [[ -f "${STATE_DIR}/${step}.done" ]]
}

# Idempotent step runner
run_step() {
    local step="$1"
    local desc="$2"
    shift 2
    if step_is_done "${step}"; then
        info "Skipping '${desc}' (already done)"
        return 0
    fi
    log "Running: ${desc}"
    mkdir -p "${LOG_DIR}"
    if "$@" 2>&1 | tee "${LOG_DIR}/${step}.log"; then
        step_done "${step}"
    else
        die "Step '${step}' failed. See ${LOG_DIR}/${step}.log"
    fi
}

# Download with resume support
fetch_source() {
    local url="$1"
    local filename="${2:-$(basename "$url")}"
    local dest="${SOURCES_DIR}/${filename}"
    if [[ -f "${dest}" ]]; then
        info "Already downloaded: ${filename}"
        return 0
    fi
    info "Downloading: ${filename}"
    wget -c --progress=bar:force -O "${dest}" "${url}" \
        || curl -L --progress-bar -C - -o "${dest}" "${url}"
}

extract_and_cd() {
    local tarball="$1"
    local dest_name="${2:-}"
    cd /tmp/flint_build
    rm -rf ./*  2>/dev/null || true
    tar xf "${SOURCES_DIR}/${tarball}"
    if [[ -n "${dest_name}" ]]; then
        cd "${dest_name}"
    else
        cd "$(tar tf "${SOURCES_DIR}/${tarball}" | head -1 | cut -d/ -f1)"
    fi
}

# ─────────────────────────────────────────────────────────────────────────────
# PRE-FLIGHT CHECKS
# ─────────────────────────────────────────────────────────────────────────────
preflight_check() {
    banner "Flint Linux — Pre-flight Check"

    [[ "${EUID}" -eq 0 ]] || die "This script must be run as root."

    local required_tools=(
        bash awk bison bzip2 chroot diff find gawk gcc g++ gzip
        m4 make patch perl python3 sed tar texinfo xz wget
    )
    local missing=()
    for tool in "${required_tools[@]}"; do
        if ! command -v "${tool}" &>/dev/null; then
            missing+=("${tool}")
        fi
    done
    if [[ ${#missing[@]} -gt 0 ]]; then
        die "Missing host tools: ${missing[*]}\nInstall them and re-run."
    fi

    # Version checks
    local bash_ver
    bash_ver=$(bash --version | head -1 | grep -oP '\d+\.\d+' | head -1)
    info "Bash: ${bash_ver}"

    local gcc_ver
    gcc_ver=$(gcc -dumpversion)
    info "GCC: ${gcc_ver}"

    local kernel_ver
    kernel_ver=$(uname -r)
    info "Host kernel: ${kernel_ver}"

    # Ensure /mnt/lfs is on a real filesystem (not tmpfs)
    if mountpoint -q "${LFS}" 2>/dev/null; then
        local fs_type
        fs_type=$(stat -f -c%T "${LFS}")
        info "LFS mount: ${LFS} (${fs_type})"
    else
        warn "${LFS} is not a separate mountpoint. Ensure your LFS partition is mounted."
    fi

    # Disk space check — need at least 50GB free
    local free_gb
    free_gb=$(df -BG "${LFS}" | awk 'NR==2{print $4}' | tr -d G)
    if [[ "${free_gb}" -lt 50 ]]; then
        warn "Only ${free_gb}GB free on ${LFS}. Recommended: 50GB+"
    else
        success "Disk space OK: ${free_gb}GB free"
    fi

    # RAM check
    local ram_gb
    ram_gb=$(free -g | awk '/^Mem:/{print $2}')
    info "RAM: ${ram_gb}GB"

    success "Pre-flight checks passed!"
}

