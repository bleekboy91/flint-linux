# ── 1.2 GCC Pass 1 ────────────────────────────────────────────────────────
build_gcc_pass1() {
    extr "gcc-14.1.0.tar.xz"
    # Unpack prerequisites into gcc source tree
    tar xf "${SRC}/mpfr-4.2.1.tar.xz"; mv mpfr-4.2.1 mpfr
    tar xf "${SRC}/gmp-6.3.0.tar.xz";  mv gmp-6.3.0  gmp
    tar xf "${SRC}/mpc-1.3.1.tar.gz";  mv mpc-1.3.1  mpc

    # Ensure 64-bit libs go to lib (not lib64) inside the sysroot
    sed -e '/m64=/s/lib64/lib/' \
        -i.orig gcc/config/i386/t-linux64

    mkdir -v build && cd build
    ../configure                                   \
        --target="${LFS_TGT}"                      \
        --prefix="${LFS}"/tools                    \
        --with-glibc-version=2.39                  \
        --with-sysroot="${LFS}"                    \
        --with-newlib                              \
        --without-headers                          \
        --enable-default-pie                       \
        --enable-default-ssp                       \
        --disable-nls                              \
        --disable-shared                           \
        --disable-multilib                         \
        --disable-threads                          \
        --disable-libatomic                        \
        --disable-libgomp                          \
        --disable-libquadmath                      \
        --disable-libssp                           \
        --disable-libvtv                           \
        --disable-libstdcxx                        \
        --enable-languages=c,c++

    make -j"${NPROC}"
    make install

    # Build limits.h for glibc compatibility
    cd ..
    cat gcc/limitx.h gcc/glimits.h gcc/limity.h > \
        "$(dirname "$("${LFS_TGT}-gcc" -print-libgcc-file-name)")/include/limits.h"
}
run_step "p1_gcc1" "GCC Pass 1" build_gcc_pass1

