phase1_toolchain() {
    banner "Phase 1 — Cross-Toolchain Build (runs as lfs user)"

    # These build steps run as lfs user for safety
    local PHASE1_SCRIPT="/tmp/flint_phase1_inner.sh"

    cat > "${PHASE1_SCRIPT}" <<'INNER'
#!/usr/bin/env bash
set -euo pipefail

# Re-import environment
source /home/lfs/.bashrc

BUILD_DIR="/tmp/flint_build"
SRC="${LFS}/sources"
TOOLS="${LFS}/tools"
STATE="${LFS}/flint_state"
LOGS="${LFS}/flint_logs"

step_done()    { mkdir -p "${STATE}"; touch "${STATE}/$1.done"; echo "  ✓ $1 done"; }
step_is_done() { [[ -f "${STATE}/$1.done" ]]; }
run_step() {
    local step="$1" desc="$2"; shift 2
    step_is_done "${step}" && { echo "  → Skipping ${desc}"; return 0; }
    echo "[PHASE1] ${desc}"
    mkdir -p "${LOGS}"
    "$@" 2>&1 | tee "${LOGS}/${step}.log"
    step_done "${step}"
}

mk() { rm -rf "${BUILD_DIR}"/*; mkdir -p "${BUILD_DIR}"; cd "${BUILD_DIR}"; }
extr() {
    cd /tmp
    rm -rf flint_build/* 2>/dev/null || true
    mkdir -p flint_build
    cd flint_build
    tar xf "${SRC}/$1"
    cd "$(tar tf "${SRC}/$1" | head -1 | cut -d/ -f1)"
}

