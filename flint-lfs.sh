setup_chroot_mounts() {
    banner "Preparing Chroot Environment"

    run_step "chroot_mounts" "Mount virtual filesystems" _mount_vfs
    run_step "chroot_dirs"   "Create essential chroot dirs" _chroot_essential_dirs
    run_step "chroot_files"  "Populate /etc essentials" _chroot_etc_files
}

_mount_vfs() {
    mkdir -p "${LFS}"/{dev,proc,sys,run}

    # Bind mount /dev
    if ! mountpoint -q "${LFS}/dev"; then
        mount -v --bind /dev "${LFS}"/dev
    fi
    if ! mountpoint -q "${LFS}/dev/pts"; then
        mount -vt devpts devpts -o gid=5,mode=0620 "${LFS}"/dev/pts
    fi
    if ! mountpoint -q "${LFS}/proc"; then
        mount -vt proc proc "${LFS}"/proc
    fi
    if ! mountpoint -q "${LFS}/sys"; then
        mount -vt sysfs sysfs "${LFS}"/sys
    fi
    if ! mountpoint -q "${LFS}/run"; then
        mount -vt tmpfs tmpfs "${LFS}"/run
    fi
    if [[ -h "${LFS}/dev/shm" ]]; then
        mkdir -p "${LFS}/$(readlink "${LFS}"/dev/shm)"
    else
        if ! mountpoint -q "${LFS}/dev/shm"; then
            mount -vt tmpfs -o nosuid,nodev tmpfs "${LFS}"/dev/shm
        fi
    fi
}

_chroot_essential_dirs() {
    mkdir -p "${LFS}"/{etc,var} "${LFS}"/usr/{bin,lib,sbin}
    for i in bin lib sbin; do
        ln -sfn usr/"$i" "${LFS}/$i" 2>/dev/null || true
    done
    case "$(uname -m)" in
        x86_64) mkdir -p "${LFS}"/lib64 ;;
    esac
}

